// Windows 11 Theme Exporter & Packaging Engine

const ThemeExporterModule = {
    
    // Generate valid Windows .theme INI text adhering strictly to Windows 11 specifications
    generateThemeIni(state, isDeskThemePack = false) {
        const isDark = state.mode === 'dark';
        const modeStr = isDark ? 'Dark' : 'Light';
        const autoColor = state.autoColorization ? 1 : 0;
        
        // Convert accent color to DWORD hex format for VisualStyles (0xAAABBGGRR)
        const rgbAccent = ColorPickerModule.hexToRgb(state.accentColor);
        const dwordAccent = ColorPickerModule.rgbToDwordHex(rgbAccent.r, rgbAccent.g, rgbAccent.b);

        // Wallpaper path logic
        let wallpaperPath = '%SystemRoot%\\web\\wallpaper\\Windows\\img0.jpg';
        if (state.wallpaperData) {
            wallpaperPath = isDeskThemePack ? 'DesktopBackground\\wallpaper.jpg' : '%SystemRoot%\\web\\wallpaper\\Windows\\img0.jpg';
        }

        // Clean Icons paths for INI file
        let iconComputer = state.icons['Computer'] ? 'Icons\\computer.ico' : '%SystemRoot%\\System32\\imageres.dll,-109';
        let iconUser = state.icons['UserFiles'] ? 'Icons\\user.ico' : '%SystemRoot%\\System32\\imageres.dll,-123';
        let iconNet = state.icons['Network'] ? 'Icons\\network.ico' : '%SystemRoot%\\System32\\imageres.dll,-25';
        let iconRecycleFull = state.icons['RecycleFull'] ? 'Icons\\recycle_full.ico' : '%SystemRoot%\\System32\\imageres.dll,-54';
        let iconRecycleEmpty = state.icons['RecycleEmpty'] ? 'Icons\\recycle_empty.ico' : '%SystemRoot%\\System32\\imageres.dll,-55';

        // Build INI structure conforming strictly to Windows 11 Aero theme spec
        let ini = `; Windows 11 Custom Theme File
; Generated by Windows 11 Theme Generator (Fluent Studio)

[Theme]
DisplayName=${state.themeName}
SetLogonBackground=0

[Control Panel\\Desktop]
Wallpaper=${wallpaperPath}
TileWallpaper=${state.wallpaperStyle === '0' ? '1' : '0'}
WallpaperStyle=${state.wallpaperStyle || '10'}
Pattern=

[VisualStyles]
Path=%ResourceDir%\\Themes\\Aero\\Aero.msstyles
ColorStyle=NormalColor
Size=NormalSize
AutoColorization=${autoColor}
ColorizationColor=${dwordAccent}
SystemMode=${modeStr}
AppMode=${modeStr}
HighContrast=0

[MasterThemeSelector]
MTSM=RJSPBS

[Sounds]
SchemeName=${state.themeName}

[Control Panel\\Colors]
`;

        // Add 21 System Colors
        const sysColors = state.sysColors;
        for (const [key, rgbVal] of Object.entries(sysColors)) {
            ini += `${key}=${rgbVal}\n`;
        }

        // Add Cursors Section with SchemeName
        ini += `\n[Control Panel\\Cursors]\nSchemeName=${state.themeName}\n`;
        const cursorKeys = ['Arrow', 'Help', 'AppStarting', 'Wait', 'Crosshair', 'IBeam', 'NWPen', 'No', 'SizeNS', 'SizeWE', 'SizeNWSE', 'SizeNESW', 'SizeAll', 'UpArrow', 'Hand'];
        cursorKeys.forEach(k => {
            let curPath = state.cursors[k] || '';
            if (curPath.startsWith('data:')) {
                curPath = `Cursors\\${k.toLowerCase()}.cur`;
            }
            ini += `${k}=${curPath}\n`;
        });
        ini += `DefaultValue=${state.themeName}\n`;

        // Add Windows 11 Sound Events Scheme
        const soundEventMap = {
            'WindowsLogon': '.Default',
            'Notification': 'SystemNotification',
            'CriticalStop': 'SystemHand',
            'Exclamation': 'SystemExclamation',
            'EmptyRecycleBin': 'EmptyRecycleBin',
            'DeviceConnect': 'DeviceConnect',
            'DeviceDisconnect': 'DeviceDisconnect',
            'Navigating': 'Navigating'
        };

        for (const [key, eventName] of Object.entries(soundEventMap)) {
            const sPath = state.sounds[key] ? `Sounds\\${key.toLowerCase()}.wav` : '';
            if (sPath) {
                ini += `\n[AppEvents\\Schemes\\Apps\\.Default\\${eventName}\\.Current]\nDefaultValue=${sPath}\n`;
            }
        }

        // Add Full Desktop Icons section using official Windows 11 CLSIDs
        ini += `\n[CLSID\\{20D04FE0-3AEA-1069-A2D8-08002B30309D}\\DefaultIcon]
DefaultValue=${iconComputer}

[CLSID\\{59031A47-3F72-44A7-89C5-5595FE6B30EE}\\DefaultIcon]
DefaultValue=${iconUser}

[CLSID\\{F02C1A0D-BE21-4350-88B0-7367FC96EF3C}\\DefaultIcon]
DefaultValue=${iconNet}

[CLSID\\{645FF040-5081-101B-9F08-00AA002F954E}\\DefaultIcon]
Full=${iconRecycleFull}
Empty=${iconRecycleEmpty}
`;

        return ini;
    },

    // Export standalone .theme INI file directly in browser
    downloadThemeFile(state) {
        const iniText = this.generateThemeIni(state, false);
        const blob = new Blob([iniText], { type: 'text/plain;charset=utf-8' });
        const url = URL.createObjectURL(blob);
        const a = document.createElement('a');
        a.href = url;
        a.download = `${this.sanitizeFilename(state.themeName)}.theme`;
        document.body.appendChild(a);
        a.click();
        document.body.removeChild(a);
        URL.revokeObjectURL(url);
    },

    // Export .deskthemepack file via server API
    async downloadDeskThemePack(state) {
        const themeName = this.sanitizeFilename(state.themeName);
        const iniText = this.generateThemeIni(state, true);

        const response = await fetch('/api/export-deskthemepack', {
            method: 'POST',
            headers: { 'Content-Type': 'application/json' },
            body: JSON.stringify({
                theme_name: themeName,
                theme_ini: iniText,
                wallpaper_data: state.wallpaperData,
                sounds_data: state.sounds,
                cursors_data: state.cursors,
                icons_data: state.icons,
                wallpaper_filename: state.wallpaperFilename || 'wallpaper.jpg'
            })
        });

        if (!response.ok) throw new Error("Failed to export .deskthemepack via server");
        const blob = await response.blob();
        const url = URL.createObjectURL(blob);
        const a = document.createElement('a');
        a.href = url;
        a.download = `${themeName}.deskthemepack`;
        document.body.appendChild(a);
        a.click();
        document.body.removeChild(a);
    },

    // Apply theme directly to Windows host machine via backend API
    async applyThemeToWindows(state) {
        const themeName = this.sanitizeFilename(state.themeName);
        const iniText = this.generateThemeIni(state, false);

        const response = await fetch('/api/apply-theme', {
            method: 'POST',
            headers: { 'Content-Type': 'application/json' },
            body: JSON.stringify({
                theme_name: themeName,
                theme_ini: iniText,
                wallpaper_data: state.wallpaperData,
                sounds_data: state.sounds,
                cursors_data: state.cursors,
                icons_data: state.icons
            })
        });

        return await response.json();
    },

    sanitizeFilename(name) {
        return (name || 'CustomTheme').replace(/[^a-zA-Z0-9_\- ]/g, '').trim().replace(/\s+/g, '_');
    }
};
